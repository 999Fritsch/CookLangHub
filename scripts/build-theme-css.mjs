// Build static/css/theme.css from the CookCLI dark-mode rules.
//
// CookCLI carries these rules inline in its base template and switches them
// with a class that a script sets from localStorage. That needs an inline
// script and an inline style, and it shows the wrong colours until the
// script runs.
//
// CookLangHub keeps the rules exactly and emits each dark rule twice:
//
//   .dark .bg-white { ... }                     an explicit choice
//   @media (prefers-color-scheme: dark) {       no choice made yet
//     html:not(.dark):not(.light) .bg-white { ... }
//   }
//
// So an explicit Light or Dark comes from the server as a class on <html>,
// and following the operating system needs no script at all.
//
// At-rules keep their nesting. An earlier version of this script flattened
// them, which lifted the rules inside `@media print` to the top level, and
// their `border-radius: 0 !important` then removed the rounded corners from
// every page. Nesting is not decoration here.

import { readFile, writeFile } from "node:fs/promises";

const SOURCE = "static/css/theme.src.css";
const TARGET = "static/css/theme.css";

const HEADER = `/*
 * Dark-mode rules taken from CookCLI.
 *
 * Copyright (c) 2021-2023 Alexey Dubovskoy
 * Licensed under the MIT License. See LICENSE-MIT-cookcli.
 *
 * GENERATED by scripts/build-theme-css.mjs from ${SOURCE}. Do not edit this
 * file. Edit the source and run \`npm run build-theme\`.
 *
 * Every dark rule appears twice: once for an explicit choice, and once for
 * a person who has made no choice and whose system asks for dark. See
 * NOTICE.
 */

`;

/** Split CSS into top-level nodes, keeping any block intact. */
function parse(css) {
  const nodes = [];
  let depth = 0;
  let start = 0;
  let inComment = false;

  for (let i = 0; i < css.length; i++) {
    if (!inComment && css[i] === "/" && css[i + 1] === "*") inComment = true;
    else if (inComment && css[i] === "*" && css[i + 1] === "/") inComment = false;
    if (inComment) continue;

    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) {
        const chunk = css.slice(start, i + 1).trim();
        if (chunk) nodes.push(chunk);
        start = i + 1;
      }
    }
  }
  return nodes;
}

/** Prelude and body of one `selector { ... }` node. */
function split(node) {
  const open = node.indexOf("{");
  return {
    prelude: node.slice(0, open).trim(),
    body: node.slice(open + 1, node.lastIndexOf("}")),
  };
}

/**
 * The selector alone, without any comment that sits in front of it.
 *
 * A node begins where the one before it ended, so a comment written above a
 * rule belongs to that rule's prelude. Reading the prelude as a selector
 * then found `/*` instead of `.dark`, and the rule was emitted once and
 * never mirrored. A person who follows the operating system therefore kept
 * the light colours for every rule that carried an explanation above it.
 */
function selectorOf(prelude) {
  return prelude.replace(/\/\*[\s\S]*?\*\//g, "").trim();
}

/** The same selector, for a person who has chosen nothing. */
function mirrorSelector(selector) {
  const parts = selector
    .split(",")
    .map((raw) => {
      const one = raw.trim();
      if (one === ".dark") return "html:not(.dark):not(.light)";
      if (one.startsWith(".dark "))
        return `html:not(.dark):not(.light) ${one.slice(".dark ".length)}`;
      // Not a dark rule. It belongs to the page frame and is emitted once.
      return null;
    })
    .filter(Boolean);

  return parts.length ? parts.join(", ") : null;
}

const source = await readFile(SOURCE, "utf8");

/*
 * Refuse a source that still holds template syntax.
 *
 * CookCLI keeps these rules inside its base template, so some of them carry
 * `{{ prefix }}` and `{% if %}`. Here they are a plain stylesheet, and a
 * browser reads that syntax as a fault. It then stops reading the file, and
 * every rule below is lost. That happened twice, and the light palette
 * showed neither of them.
 *
 * A comment can name the syntax, so comments are taken out first. The
 * lengths stay the same, so the line number still points at the rule.
 */
const withoutComments = source.replace(/\/\*[\s\S]*?\*\//g, (block) =>
  block.replace(/[^\n]/g, " "),
);
const templateSyntax = withoutComments.match(
  /\{\{[\s\S]{0,60}?\}\}|\{%[\s\S]{0,60}?%\}/,
);
if (templateSyntax) {
  const line = source.slice(0, templateSyntax.index).split("\n").length;
  console.error(
    `${SOURCE}:${line}: template syntax in a stylesheet: ${templateSyntax[0]}`,
  );
  console.error(
    "A browser reads this as a fault and stops reading the file. Write the",
  );
  console.error("address of this application instead.");
  process.exit(1);
}

const kept = [];
const mirrored = [];

for (const node of parse(source)) {
  const { prelude, body } = split(node);
  const selector = selectorOf(prelude);

  if (selector.startsWith("@")) {
    // An at-rule keeps its own nesting. `@media print` in particular must
    // never have its contents lifted out.
    kept.push(node);

    // A dark rule inside an at-rule is left alone: nesting one media query
    // inside another is not valid, and CookCLI has none that need it.
    continue;
  }

  kept.push(node);

  const mirror = mirrorSelector(selector);
  if (mirror) mirrored.push(`  ${mirror} {${body}}`);
}

const output =
  HEADER +
  kept.join("\n\n") +
  "\n\n@media (prefers-color-scheme: dark) {\n" +
  mirrored.join("\n") +
  "\n}\n";

await writeFile(TARGET, output, "utf8");

console.log(
  `theme.css: ${kept.length} top-level nodes kept, ${mirrored.length} dark rules mirrored`,
);
